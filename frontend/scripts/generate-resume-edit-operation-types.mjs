import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(
  scriptDirectory,
  "../../backend/app/services/agent/resume_edit_operation.schema.json",
);
const resumeDocumentSchemaPath = resolve(
  scriptDirectory,
  "../../backend/app/services/resume_document.schema.json",
);
const outputPath = resolve(
  scriptDirectory,
  "../src/types/resume-edit-operation.generated.ts",
);
const writeMode = process.argv.includes("--write");

function resolveReference(rootSchema, reference, resumeDocumentSchema) {
  let referencedRoot = rootSchema;
  let pointer = reference;

  if (!reference.startsWith("#/")) {
    const resumeDocumentId = resumeDocumentSchema.$id;
    if (
      typeof resumeDocumentId !== "string" ||
      !reference.startsWith(`${resumeDocumentId}#/`)
    ) {
      throw new Error(`Unsupported schema reference: ${reference}`);
    }
    referencedRoot = resumeDocumentSchema;
    pointer = reference.slice(resumeDocumentId.length);
  }

  const resolved = pointer
    .slice(2)
    .split("/")
    .map((part) => part.replaceAll("~1", "/").replaceAll("~0", "~"))
    .reduce((value, part) => value?.[part], referencedRoot);

  return { referencedRoot, resolved };
}

function propertyName(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)
    ? name
    : JSON.stringify(name);
}

/**
 * Render the deliberately small JSON Schema subset used by the operation
 * contract. Unsupported keywords fail generation instead of silently
 * broadening the frontend type.
 */
function renderType(schema, rootSchema, resumeDocumentSchema, depth = 0) {
  if (!schema || typeof schema !== "object") {
    throw new Error("Every rendered schema node must be an object.");
  }

  if (typeof schema["x-typescript-type"] === "string") {
    return schema["x-typescript-type"];
  }

  if (typeof schema.$ref === "string") {
    const { referencedRoot, resolved } = resolveReference(
      rootSchema,
      schema.$ref,
      resumeDocumentSchema,
    );
    return renderType(
      resolved,
      referencedRoot,
      resumeDocumentSchema,
      depth,
    );
  }

  if ("const" in schema) {
    return JSON.stringify(schema.const);
  }

  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }

  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf
      .map((branch) =>
        renderType(branch, rootSchema, resumeDocumentSchema, depth),
      )
      .join(`\n${"  ".repeat(depth)}| `);
  }

  if (schema.type === "string") {
    return "string";
  }
  if (schema.type === "integer" || schema.type === "number") {
    return "number";
  }
  if (schema.type === "boolean") {
    return "boolean";
  }
  if (schema.type === "array") {
    return `${renderType(schema.items, rootSchema, resumeDocumentSchema, depth)}[]`;
  }
  if (schema.type === "object") {
    const properties = schema.properties ?? {};
    const required = new Set(schema.required ?? []);
    const indent = "  ".repeat(depth);
    const childIndent = "  ".repeat(depth + 1);
    const fields = Object.entries(properties).map(([name, propertySchema]) => {
      const optional = required.has(name) ? "" : "?";
      return `${childIndent}${propertyName(name)}${optional}: ${renderType(
        propertySchema,
        rootSchema,
        resumeDocumentSchema,
        depth + 1,
      )};`;
    });

    return `{\n${fields.join("\n")}\n${indent}}`;
  }

  throw new Error(
    `Unsupported schema node: ${JSON.stringify(schema, null, 2)}`,
  );
}

const [schema, resumeDocumentSchema] = await Promise.all(
  [schemaPath, resumeDocumentSchemaPath].map(async (path) =>
    JSON.parse(await readFile(path, "utf8")),
  ),
);
const renderedType = renderType(schema, schema, resumeDocumentSchema, 1);
const generated = `// Generated by scripts/generate-resume-edit-operation-types.mjs.
// Edit the backend JSON Schema, then run pnpm generate:agent-contract.
import type { ResumeSection, ResumeSectionItem } from "@/types/resume";

export type ResumeEditOperation =
  ${renderedType};
`;

if (writeMode) {
  await writeFile(outputPath, generated, "utf8");
} else {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // The error below provides the same recovery command for missing or stale output.
  }

  if (current !== generated) {
    throw new Error(
      "Generated resume edit operation types are stale. " +
        "Run `pnpm generate:agent-contract` from frontend.",
    );
  }
}
