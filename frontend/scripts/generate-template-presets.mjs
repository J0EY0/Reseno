import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const presetPath = resolve(
  scriptDirectory,
  "../../backend/app/services/template_presets.json",
);
const outputPath = resolve(
  scriptDirectory,
  "../src/lib/template-presets.generated.ts",
);
const writeMode = process.argv.includes("--write");
const starterIds = new Set([
  "earlyCareer",
  "experienced",
  "executive",
  "research",
]);

const presets = JSON.parse(await readFile(presetPath, "utf8"));
if (!presets || typeof presets !== "object" || Array.isArray(presets)) {
  throw new Error("Built-in template presets must be a non-empty object.");
}

for (const [templateId, preset] of Object.entries(presets)) {
  if (
    !templateId ||
    !preset ||
    typeof preset !== "object" ||
    Array.isArray(preset) ||
    !starterIds.has(preset.starter) ||
    !("layout" in preset) ||
    !("typography" in preset) ||
    !("settings" in preset)
  ) {
    throw new Error(
      `Built-in template preset ${templateId || "<empty>"} is malformed.`,
    );
  }
}

const generated = `// Generated by scripts/generate-template-presets.mjs.
// Edit backend/app/services/template_presets.json, then run pnpm generate:template-presets.
export const builtinTemplatePresets = ${JSON.stringify(presets, null, 2)} as const

export type GeneratedBuiltinTemplateId = keyof typeof builtinTemplatePresets
`;

if (writeMode) {
  await writeFile(outputPath, generated, "utf8");
} else {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // The error below provides the same recovery command for missing or stale output.
  }

  if (current !== generated) {
    throw new Error(
      "Generated template presets are stale. " +
        "Run `pnpm generate:template-presets` from frontend.",
    );
  }
}
